def describe(code: str | None) -> str | None:
    """Meaning of a code as stored in `pension_inquiries.error_code`.

    The ranges don't overlap: 1–17 file level, 100–126 record errors,
    1001+ insurer answers. Our own non-numeric codes (e.g.
    `identity_not_configured`) return None."""
    c = (code or "").strip()
    if not c.isdigit():
        return None
    n = int(c)
    if n < 100:
        return FILE_LEVEL_CODES.get(c)
    if n < 1000:
        return RECORD_ERROR_CODES.get(c)
    return INSURER_ANSWER_CODES.get(c)
